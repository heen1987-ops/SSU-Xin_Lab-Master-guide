"""핸드북·서식 Markdown에서 docs/html 열람본을 생성하거나 최신성을 검사한다."""
from pathlib import Path
from urllib.parse import quote, unquote, urlsplit
import argparse
import html
import re
import sys
import unicodedata

try:
    import markdown
except ImportError:
    sys.exit('먼저 python -m pip install -r scripts/requirements-docs.txt 를 실행하세요.')

ROOT = Path(__file__).resolve().parents[1]
PAGES = {
    'handbook/README.md': ('handbook.html', '전체 문서 지도'),
    'handbook/01_학술총무_운영.md': ('coordinator.html', '학술총무 운영'),
    'handbook/02_석박사_검토기준.md': ('degree-review.html', '석박사 검토 기준'),
    'handbook/03_연구방법별_검토.md': ('method-review.html', '연구방법별 검토'),
    'handbook/04_SSU논문스킬_활용.md': ('skill-workflow.html', 'SSU 논문 스킬'),
    'handbook/05_문서관리와_출처.md': ('document-policy.html', '문서관리와 출처'),
    'templates/README.md': ('templates.html', '서식 모음'),
    'templates/01_검토요청.md': ('form-request.html', '검토 요청서'),
    'templates/02_연구현황판.md': ('form-status.html', '연구 현황판'),
    'templates/03_검토와수정.md': ('form-review.html', '검토·수정 기록'),
    'templates/04_기여연결.md': ('form-contribution.html', '기여 연결표'),
    'templates/05_인수인계.md': ('form-handoff.html', '인수인계서'),
    'templates/06_규정확인.md': ('form-requirements.html', '규정 확인표'),
}
BY_PATH = {(ROOT / source).resolve(): target for source, (target, _) in PAGES.items()}
REPO_URL = 'https://github.com/heen1987-ops/SSU-Xin_Lab-Master-guide/blob/main/'


def slug(value, separator):
    value = html.unescape(re.sub('<[^>]+>', '', value)).lower()
    return ''.join(c for c in value if c in ('-', '_', ' ') or
                   unicodedata.category(c)[0] in ('L', 'N', 'M')).replace(' ', separator)


def rewrite_link(match, source):
    value = html.unescape(match[1])
    parsed = urlsplit(value)
    if parsed.scheme or parsed.netloc or not parsed.path:
        return match[0]
    target = (source.parent / unquote(parsed.path)).resolve()
    generated_targets = {ROOT / 'docs' / output for output, _ in PAGES.values()}
    if not target.exists() and target not in generated_targets:
        raise ValueError(f'{source.name}: 없는 링크 {value}')
    if target in BY_PATH:
        link = BY_PATH[target]
    elif target == ROOT / 'README.md':
        link = 'index.html'
    elif target.is_relative_to(ROOT / 'docs'):
        link = target.relative_to(ROOT / 'docs').as_posix()
    else:
        link = REPO_URL + quote(target.relative_to(ROOT).as_posix())
    if parsed.query:
        link += '?' + parsed.query
    if parsed.fragment:
        link += '#' + parsed.fragment
    return 'href="' + html.escape(link, quote=True) + '"'


def render(source_name, output_name, label):
    source = ROOT / source_name
    md = markdown.Markdown(extensions=['tables', 'fenced_code', 'toc'],
                           extension_configs={'toc': {'slugify': slug}})
    body = md.convert(source.read_text(encoding='utf-8-sig'))
    body = re.sub(r'href="([^"]+)"', lambda m: rewrite_link(m, source), body)
    body = body.replace('<table>', '<div class="table-scroll" role="region" aria-label="표: 좌우로 스크롤할 수 있습니다" tabindex="0"><table>')
    body = body.replace('</table>', '</table></div>')
    heading = re.search(r'<h1[^>]*>(.*?)</h1>', body)
    title = heading.group(1)
    heading_html = heading.group(0)
    body = body.replace(heading_html, '', 1)
    nav = ''.join(f'<a href="{out}"' + (' aria-current="page"' if out == output_name else '')
                  + f'>{html.escape(name)}</a>' for key, (out, name) in PAGES.items()
                  if key.startswith('handbook/') or key == 'templates/README.md')
    download = ''
    if source_name.startswith('templates/') and source.name != 'README.md':
        download = f'<a class="download" href="assets/templates/{quote(source.name)}" download>빈 서식 내려받기 · Markdown</a>'
    if output_name == 'templates.html':
        download = '<p class="notice">서식 제목을 누르면 작성 항목과 내려받기 링크가 열립니다. 작성본은 연구실 내부 공간에 보관하세요.</p>'
    return f'''<!doctype html>
<!-- Generated by scripts/build_handbook.py from {source_name}. Edit Markdown, not this file. -->
<html lang="ko"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>{title} | 신랩 논문 가이드</title>
<meta name="description" content="신랩 석사·박사 논문 작성과 학술총무 검토를 위한 {html.escape(label)}">
<link rel="stylesheet" href="assets/handbook.css"></head>
<body><a class="skip-link" href="#main-content">본문 바로가기</a>
<header class="masthead"><a href="index.html" class="brand">Xin Lab <span>논문 작성·검토 가이드</span></a>
<nav aria-label="공통 메뉴"><a href="handbook.html">핸드북</a><a href="templates.html">서식</a><a href="research-workbench.html">연구 작업대</a><a href="requirements.html">제출 요건</a></nav></header>
<div class="layout"><aside><p class="eyebrow">RESEARCH HANDBOOK</p><nav aria-label="핸드북 목차">{nav}</nav>
<p class="sidebar-note">연구자와 학술총무가 함께 쓰는 실무 안내<br>2026.10.15 개편</p></aside>
<main id="main-content" tabindex="-1"><p class="breadcrumb">신랩 / {html.escape(label)}</p>
{heading_html}{download}<details class="page-toc"><summary>이 문서의 목차</summary>{md.toc}</details>
<article>{body}</article><footer>운영 절차는 조정 가능한 연구실 제안입니다. 규정·사례의 확인 범위는 각 문서에서 확인하세요.<br>
<a href="handbook.html">전체 문서 지도</a> · <a href="templates.html">서식 모음</a> · <a href="index.html">연구 단계 가이드</a></footer>
</main></div></body></html>
'''.encode('utf-8')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='파일을 쓰지 않고 생성본 일치 검사')
    args = parser.parse_args()
    outputs = {}
    for source, (target, label) in PAGES.items():
        rendered = render(source, target, label)
        for folder in ('docs', 'html'):
            outputs[ROOT / folder / target] = rendered
    for source in sorted((ROOT / 'templates').glob('[0-9]*.md')):
        for folder in ('docs', 'html'):
            outputs[ROOT / folder / 'assets/templates' / source.name] = source.read_bytes()
    stale = []
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_bytes() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    if stale:
        sys.exit('생성본 갱신 필요:\n' + '\n'.join(stale))
    print(f'{"일치 확인" if args.check else "생성 완료"}: 웹 {len(PAGES)}종 × 2, 서식 6종 × 2')


if __name__ == '__main__':
    main()
