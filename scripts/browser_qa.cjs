const {chromium}=require('playwright');
const fs=require('fs');
const path=require('path');
const out=path.resolve(process.env.GUIDE_QA_OUTPUT || '.qa');
fs.mkdirSync(out,{recursive:true});
const results=[];
function check(name,value){results.push({name,pass:!!value});if(!value)console.log('FAIL',name);}
(async()=>{
 const browser=await chromium.launch({headless:true,...(process.env.GUIDE_BROWSER_PATH ? {executablePath:process.env.GUIDE_BROWSER_PATH} : {})});
 const context=await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
 const page=await context.newPage(); const errors=[];
 page.on('pageerror',error=>errors.push(error.message));
 const base=process.env.GUIDE_BASE_URL || 'http://127.0.0.1:8731/';
 await page.goto(base,{waitUntil:'networkidle'});
 check('공통 홈 제목',(await page.locator('h1').innerText()).includes('지금 필요한 단계'));
 check('7개 단계 진입',await page.locator('.stage-card').count()===7);
 await page.keyboard.press('Tab');
 check('첫 키보드 초점은 본문 바로가기',await page.locator('.skip-link').evaluate(el=>el===document.activeElement));
 await page.keyboard.press('Enter');
 check('본문 초점 이동',await page.locator('main').evaluate(el=>el===document.activeElement));
 await page.keyboard.press('Control+k');
 check('검색 열림',await page.locator('dialog').evaluate(el=>el.open));
 check('검색 입력 초점',await page.locator('#guide-search-input').evaluate(el=>el===document.activeElement));
 await page.locator('#guide-search-input').fill('zzzzunmatched');
 check('검색 빈 결과',await page.locator('[role=status]').innerText()==='검색 결과가 없습니다. 다른 단어나 상위 단계로 검색하세요.');
 await page.keyboard.press('Escape');
 check('Escape로 닫힘',!(await page.locator('dialog').evaluate(el=>el.open)));
 await page.locator('.search-trigger-btn').click();
 await page.locator('#guide-search-input').fill('연구설계');
 check('검색 결과 제공',await page.locator('dialog li a').count()>0);
 await page.locator('dialog button').click();
 check('검색 종료 후 버튼 초점 복원',await page.locator('.search-trigger-btn').evaluate(el=>el===document.activeElement));
 await page.locator('.search-trigger-btn').click();
 await page.locator('#guide-search-input').fill('선행연구');
 await page.locator('dialog a[href="#literature"]').click();
 await page.waitForFunction(()=>document.activeElement?.id==='literature');
 check('검색 선택 후 대상에 초점 유지',await page.locator('#literature').evaluate(el=>el===document.activeElement));
 const before=await page.locator('html').getAttribute('data-theme');
 await page.locator('#theme-toggle').click();
 const after=await page.locator('html').getAttribute('data-theme');
 check('테마 전환',before!==after);
 await page.reload({waitUntil:'networkidle'});
 check('테마 저장',await page.locator('html').getAttribute('data-theme')===after);
 if(after==='dark')await page.locator('#theme-toggle').click();
 await page.locator('#c1').check(); await page.reload({waitUntil:'networkidle'});
 check('체크리스트 저장',await page.locator('#c1').isChecked());
 const parallel=await context.newPage();
 await parallel.goto(base+'empirical.html');
 await page.locator('#c2').check();
 const otherBox=parallel.locator('#checklist input[type=checkbox]').first();
 const otherId=await otherBox.getAttribute('id');
 await otherBox.check();
 const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('thesis-guide-checklist-unified-v1')));
 check('여러 탭의 체크 상태 병합',saved.c2===true&&saved[otherId]===true);
 await parallel.close();
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.screenshot({path:path.join(out,'desktop-home.png')});
 await page.locator('#stages').scrollIntoViewIfNeeded();
 await page.screenshot({path:path.join(out,'desktop-stages.png')});
 for(const filename of ['index.html','requirements.html','empirical.html','experiment.html','research-workbench.html']){
  for(const width of [1440,390,320]){
   await page.setViewportSize({width,height:900});
   await page.goto(base+filename,{waitUntil:'networkidle'});
   const overflow=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth,body:document.body.scrollWidth}));
   check(filename+' '+width+'px 가로 넘침 없음',Math.max(overflow.scroll,overflow.body)<=width+1);
   if(Math.max(overflow.scroll,overflow.body)>width+1)console.log('OVERFLOW',filename,width,JSON.stringify(await page.evaluate(()=>[...document.querySelectorAll('body *')].filter(e=>{const r=e.getBoundingClientRect();return r.right>innerWidth+2&&r.width>0}).slice(0,12).map(e=>({tag:e.tagName,cls:e.className,width:e.getBoundingClientRect().width})))));
   check(filename+' '+width+'px 탐색과 검색 표시',await page.locator('.search-trigger-btn').isVisible());
   if(width===390){await page.screenshot({path:path.join(out,filename.replace('.html','')+'-mobile.png')});}
  }
 }
 await page.setViewportSize({width:1440,height:1000});
 await page.goto(base);
 await page.locator('.search-trigger-btn').click();
 await page.locator('#guide-search-input').fill('원문검수');
 await page.locator('dialog a[href="research-workbench.html#fulltext"]').click();
 await page.waitForURL('**/research-workbench.html#fulltext');
 check('홈 검색에서 원문검수로 이동',await page.locator('#fulltext').isVisible());
 await page.locator('.search-trigger-btn').click();
 await page.locator('#guide-search-input').fill('반증');
 await page.locator('dialog a[href="#problem"]').click();
 await page.waitForFunction(()=>document.activeElement?.id==='problem');
 check('연구설계 페이지 검색 초점',await page.locator('#problem').evaluate(el=>el===document.activeElement));
 await context.grantPermissions(['clipboard-read','clipboard-write']);
 await page.locator('#problem .table-copy').click();
 const copied=await page.evaluate(()=>navigator.clipboard.readText());
 check('문제정의 연결표 내용 복사',copied.includes('RQ ID')&&copied.includes('반증 조건'));
 await page.locator('#workbook details summary').click();
 check('요청문 펼치기',await page.locator('#workbook details pre').isVisible());
 const downloadEvent=page.waitForEvent('download');
 await page.locator('#workbook a[download]').click();
 const download=await downloadEvent;
 const downloaded=await download.path();
 check('공통 작업지 실제 다운로드',download.suggestedFilename()==='research-workbook.md'&&!!downloaded);
 const workbook=fs.readFileSync(downloaded,'utf8');
 check('작업지 핵심 작성표 포함',['문제정의','분석계획','OCR','혼합연구'].every(word=>workbook.includes(word)));
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.screenshot({path:path.join(out,'research-workbench-desktop.png')});
 for(const [old,target,hash] of [['master.html','index.html','roadmap'],['석사과정.html','index.html','format'],['phd.html','requirements.html','record'],['박사과정.html','requirements.html','exam'],['실증논문가이드.html','empirical.html','overview'],['실험논문가이드.html','experiment.html','overview']]){
  await page.goto(base+encodeURI(old)+'?from=legacy#'+hash,{waitUntil:'networkidle'});
  check(old+' query·앵커 보존',page.url()===base+target+'?from=legacy#'+hash);
  check(old+' 실제 앵커 존재',await page.locator('#'+hash).count()===1);
 }
 const nojs=await browser.newContext({javaScriptEnabled:false});const staticPage=await nojs.newPage();
 await staticPage.goto(base+'phd.html');
 check('JavaScript 없이 호환 링크 제공',await staticPage.locator('#destination').getAttribute('href')==='requirements.html');
 await staticPage.goto(base);check('JavaScript 없이 7단계 내용 제공',await staticPage.locator('.stage-card').count()===7);
 await nojs.close();
 const blocked=await browser.newContext();const bp=await blocked.newPage();
 await bp.addInitScript(()=>{Storage.prototype.getItem=()=>{throw new Error('blocked')};Storage.prototype.setItem=()=>{throw new Error('blocked')};});
 await bp.goto(base);await bp.locator('#c1').check();await bp.locator('#theme-toggle').click();
 check('저장소 차단 시에도 입력·테마 동작',await bp.locator('#c1').isChecked());
 await blocked.close();
 check('브라우저 JavaScript 오류 없음',errors.length===0);
 fs.writeFileSync(path.join(out,'browser-results.json'),JSON.stringify({results,errors},null,2));
 console.log(JSON.stringify({total:results.length,passed:results.filter(x=>x.pass).length,errors,out}));
 await browser.close();
 if(results.some(x=>!x.pass))process.exitCode=1;
})().catch(e=>{console.error(e);process.exit(1)});
